/** 交给 AI 导演的卡片简报：卡片是骨架，用户给的内容优先，卡片没写的细节由导演按产品自己编。 */
export function dramaCardBrief(card: DramaCard) {
    const style = DRAMA_CARD_STYLES[card.style];
    return [
        `【故事卡片】${card.title}：${card.logline}`,
        `【画风】${style.label}。${style.look}`,
        `【形式】${card.dialogue ? "角色在画面里亲口说台词" : "第一人称旁白讲述"}，${card.captions ? "要字幕" : "不要字幕"}，${card.ratio}，约 ${card.durationSeconds} 秒`,
        `【产品怎么出场】${card.product}`,
        "【剧情节拍】（百分比是占全片时长的位置）",
        ...card.beats.map((beat) => `- ${beat}`),
        `【角色】${card.cast}`,
        `【语气和声音】${card.tone}`,
        "【规则】用户的文字和上传的素材可以改动卡片的任何部分；用户没改的地方照卡片来。只用用户给的产品卖点、优惠和口号，不要编造功效、价格或评价；用户没给名字就按产品类型起一个，不能用真实品牌。卡片里没写的名字、地点、台词、道具和笑点，按产品、它的买家、使用场合和没有它会出什么问题来编，不要用最先想到的套路。默认马来西亚的场景、人名和说话方式。",
    ].join("\n");
}
